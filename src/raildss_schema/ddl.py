"""Generate PostgreSQL / PostGIS DDL from the canonical models (issue #4).

Type mapping: ``str`` -> TEXT, ``int`` -> BIGINT, ``float`` -> DOUBLE PRECISION, ``bool`` -> BOOLEAN,
``date`` -> DATE, ``datetime`` -> TIMESTAMPTZ, ``Literal[...]`` -> TEXT with a CHECK constraint,
nested models / lists / tuples / dicts -> JSONB. Required, non-optional fields are NOT NULL.

``operational_point`` also gets a generated PostGIS column ``geom geometry(Point, 4326)``.
The committed migration files are produced by ``python -m raildss_schema generate``.
"""

from __future__ import annotations

import datetime as dt
import types
import typing
from typing import Any, Literal, Union

from pydantic import BaseModel
from pydantic.fields import FieldInfo

from raildss_schema.base import Stamped
from raildss_schema.entities import ENTITIES, OperationalPoint

WGS84_SRID = 4326
JSONB = "JSONB"
SCALARS: dict[type, str] = {
    str: "TEXT",
    bool: "BOOLEAN",
    int: "BIGINT",
    float: "DOUBLE PRECISION",
    dt.date: "DATE",
    dt.datetime: "TIMESTAMPTZ",
}


def _unwrap(annotation: Any) -> tuple[Any, bool]:
    """Return (inner annotation, is_optional), stripping Annotated and ``X | None``."""
    optional = False
    while True:
        origin = typing.get_origin(annotation)
        if origin is typing.Annotated:
            annotation = typing.get_args(annotation)[0]
            continue
        if origin in (Union, types.UnionType):
            args = [a for a in typing.get_args(annotation) if a is not type(None)]
            optional = optional or len(args) < len(typing.get_args(annotation))
            if len(args) == 1:
                annotation = args[0]
                continue
            return annotation, optional
        return annotation, optional


def column_type(annotation: Any) -> tuple[str, tuple[str, ...] | None, bool]:
    """Return (sql_type, literal_choices or None, is_json) for a field annotation."""
    inner, _ = _unwrap(annotation)
    if typing.get_origin(inner) is Literal:
        return "TEXT", tuple(str(a) for a in typing.get_args(inner)), False
    if isinstance(inner, type):
        for py, sql in SCALARS.items():
            if inner is py:
                return sql, None, False
        if issubclass(inner, BaseModel):
            return JSONB, None, True
    return JSONB, None, True


def is_json_field(field: FieldInfo) -> bool:
    return column_type(field.annotation)[2]


def is_nullable(field: FieldInfo) -> bool:
    return _unwrap(field.annotation)[1] or not field.is_required()


def create_table(model: type[Stamped]) -> str:
    cols: list[str] = []
    for name, field in model.model_fields.items():
        sql_type, choices, _ = column_type(field.annotation)
        nullable = _unwrap(field.annotation)[1]
        col = f"    {name} {sql_type}"
        if not nullable:
            col += " NOT NULL"
        if choices is not None:
            options = ", ".join("'" + c.replace("'", "''") + "'" for c in choices)
            col += f" CHECK ({name} IN ({options}))"
        cols.append(col)
    if model is OperationalPoint:
        cols.append(
            f"    geom geometry(Point, {WGS84_SRID}) GENERATED ALWAYS AS "
            f"(CASE WHEN lon IS NOT NULL AND lat IS NOT NULL "
            f"THEN ST_SetSRID(ST_MakePoint(lon, lat), {WGS84_SRID}) END) STORED"
        )
    cols.append(f"    PRIMARY KEY ({', '.join(model.__pk__)})")
    return f"CREATE TABLE {model.__table__} (\n" + ",\n".join(cols) + "\n);"


def up_sql() -> str:
    parts = [
        "-- 0001 canonical schema v1. GENERATED by `python -m raildss_schema generate`. Do not edit.",
        "CREATE EXTENSION IF NOT EXISTS postgis;",
    ]
    parts += [create_table(m) for m in ENTITIES]
    return "\n\n".join(parts) + "\n"


def down_sql() -> str:
    parts = ["-- 0001 canonical schema v1 (down). GENERATED by `python -m raildss_schema generate`."]
    parts += [f"DROP TABLE IF EXISTS {m.__table__};" for m in reversed(ENTITIES)]
    return "\n\n".join(parts) + "\n"
