"""Command line for the parameter register.

python -m raildss_params lint [PATH]
python -m raildss_params dummy-report [--write docs/params/dummy-values.md]
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import yaml

from raildss_params.register import Register, default_path, lint, load

DUMMY_REPORT = Path("docs") / "params" / "dummy-values.md"


def dummy_report(register: Register) -> str:
    """Markdown list of every DUMMY value (spec C-14), regenerated from the register."""
    lines = [
        "# Dummy parameter values",
        "",
        "Generated by `python -m raildss_params dummy-report --write` from `config/parameters.yaml`.",
        "Do not edit by hand. These values come from open-internet secondary sources or are",
        "placeholders (spec C-14); they must be replaced if better sources appear.",
        "",
        f"Register version: `{register.register_version}`",
        "",
        "| Key | Value | Unit | Provenance | Notes |",
        "|---|---|---|---|---|",
    ]
    for p in sorted(register.by_status("DUMMY"), key=lambda q: q.key):
        val = json.dumps(p.value, ensure_ascii=False) if p.value is not None else f"ref {p.value_ref}"
        notes = " ".join((p.notes or "").split()).replace("|", "\\|")
        lines.append(f"| `{p.key}` | `{val}` | {p.unit or ''} | {p.provenance} | {notes} |")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="python -m raildss_params")
    sub = ap.add_subparsers(dest="cmd", required=True)
    p_lint = sub.add_parser("lint", help="lint the register (exit 1 on problems)")
    p_lint.add_argument("path", nargs="?", type=Path)
    p_dummy = sub.add_parser("dummy-report", help="print or write the DUMMY values report")
    p_dummy.add_argument("--write", nargs="?", const=DUMMY_REPORT, type=Path)
    args = ap.parse_args(argv)

    if args.cmd == "lint":
        path = args.path or default_path()
        problems = lint(yaml.safe_load(path.read_text(encoding="utf-8")))
        for prob in problems:
            print(f"FAIL  {prob}")
        print(f"{path}: {'FAILED' if problems else 'OK'} ({len(problems)} problem(s))")
        return 1 if problems else 0

    report = dummy_report(load())
    if args.write:
        args.write.parent.mkdir(parents=True, exist_ok=True)
        args.write.write_text(report, encoding="utf-8", newline="\n")
        print(f"wrote {args.write}")
    else:
        sys.stdout.write(report)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
