"""SCN-22 over the 27 real freight days against the historical reference BL-5 (issue #166; DSC-20, BL-5).

Each real day of SCN-22 is replayed in the twin (BL-0: its seed, its freight day, the nominal passenger
WTT, the freight halts of ``twin.freight_detention``). Per day the runner reports what the log can be
compared with:

* the freight through-transit, over loads whose path calls at the reference's
  ``through_transit_min_stations`` or more section stations, as BL-5 counts them;
* the freight dwell at VZM: P90 and the share of stops over the log's long-dwell threshold;
* for the twin only, the section punctuality A2 (the log has no passenger actuals).

The rows are kept in ``docs/kpi/real-days-bl5.json`` so that the days can be run in batches
(``--days``); the Markdown report is rendered from all the rows.
"""

from __future__ import annotations

import json
import statistics
from pathlib import Path
from typing import Any

from raildss_twin import kpi_eval, run, scenario
from raildss_twin.bl0_check import OUT_DIR, P90, REFERENCE_JSON, SECONDS_PER_HOUR, station_dwell

ROWS_JSON = OUT_DIR / "real-days-bl5.json"
REPORT_MD = OUT_DIR / "real-days-bl5.md"
DWELL_OP = "VZM"


def _q(values: list[float], q: float) -> float | None:
    s = sorted(values)
    return s[min(len(s) - 1, int(q * len(s)))] if s else None


def _median(values: list[float]) -> float | None:
    return statistics.median(values) if values else None


def day_row(world: run.World, sc: scenario.Scenario, reference: dict[str, Any]) -> dict[str, Any]:
    """The comparison row of one real day (``sc`` is one of ``scenario.day_scenarios(SCN-22)``)."""
    kw = scenario.run_kwargs(sc, world)
    sims: list[Any] = []
    report = kpi_eval.run_arm(
        world,
        sc.wtt_date,
        "BL-0",
        f"{sc.id}/{sc.wtt_date}",
        directives=kw["directives"],
        seed=kw["seed"],
        day_instance=kw["day_instance"],
        setup=kw["setup"],
        sim_out=sims,
    )
    sim = sims[0]
    layout = world.layout
    min_stations = int(reference["parameters"]["through_transit_min_stations"])  # as BL-5 counts them
    through = [
        (t.exit_s - t.plan.entry_s) / SECONDS_PER_HOUR
        for t in sim.trains
        if t.plan.kind == "freight"
        and t.exit_s is not None
        and t.plan.entry_s >= 0
        and sum(1 for n in t.plan.nodes if not layout.ops[n.op].is_halt) >= min_stations
    ]
    dwell = station_dwell(sim, DWELL_OP)
    long_min = float(reference["parameters"]["long_dwell_min"])
    day = sc.wtt_date.isoformat()
    hist_t = reference["through_transit_h"]["by_day"].get(day, {})
    hist_d = reference["dwell_min"]["by_day"].get(day, {}).get(DWELL_OP, {})
    return {
        "day": day,
        "twin_transit_median_h": _median(through),
        "twin_transit_n": len(through),
        "hist_transit_median_h": hist_t.get("median"),
        "hist_transit_n": hist_t.get("n"),
        "twin_vzm_p90_min": _q(dwell, P90),
        "twin_vzm_share_long": (sum(1 for x in dwell if x > long_min) / len(dwell)) if dwell else None,
        "twin_vzm_calls": len(dwell),
        "hist_vzm_p90_min": hist_d.get("p90"),
        "hist_vzm_share_long": hist_d.get("share_over_long"),
        "twin_a2_pct": report.kpis["A2_section_punctuality_pct"],
        "twin_trains_exited": report.kpis["B1_trains_exited"],
    }


def load_rows(path: Path = ROWS_JSON) -> dict[str, dict[str, Any]]:
    if not path.exists():
        return {}
    return {r["day"]: r for r in json.loads(path.read_text(encoding="utf-8"))["rows"]}


def save_rows(rows: dict[str, dict[str, Any]], path: Path = ROWS_JSON) -> None:
    doc = {"scenario": "SCN-22", "rows": [rows[k] for k in sorted(rows)]}
    path.write_text(json.dumps(doc, indent=1) + "\n", encoding="utf-8", newline="\n")


def _fmt(v: Any, spec: str = ".2f") -> str:
    return "-" if v is None else format(v, spec)


def render(rows: dict[str, dict[str, Any]], reference: dict[str, Any]) -> str:
    days = [rows[k] for k in sorted(rows)]
    month_t = reference["through_transit_h"]["month"]
    month_d = reference["dwell_min"]["month"][DWELL_OP]
    medians = [r["twin_transit_median_h"] for r in days if r["twin_transit_median_h"] is not None]
    p90s = [r["twin_vzm_p90_min"] for r in days if r["twin_vzm_p90_min"] is not None]
    shares = [r["twin_vzm_share_long"] for r in days if r["twin_vzm_share_long"] is not None]
    a2 = [r["twin_a2_pct"] for r in days]
    out = [
        "# SCN-22: the 27 real freight days against BL-5 (issue #166; DSC-20, BL-5)",
        "",
        "Generated by `python -m raildss_twin real-days --write` (rows kept in `real-days-bl5.json`; a "
        "batch of days with `--days`). Each real day of SCN-22 is replayed in the twin under BL-0 (seed "
        "22, the day's freight instance, the nominal passenger WTT, the freight halts of "
        "`twin.freight_detention`); its trace hash is recorded in `scenarios/v0/SCN-22.yaml` (`real_days`). "
        f"Through-transit counts loads calling at {reference['parameters']['through_transit_min_stations']} "
        "or more section stations, as BL-5 does. "
        "The log has no passenger actuals, so A2 is the twin's only.",
        "",
        f"Days run: {len(days)} of 27.",
        "",
        "| | Twin (BL-0) | BL-5 (history) |",
        "|---|---:|---:|",
        f"| Median of the daily median through-transit (h) | {_fmt(_median(medians))} | "
        f"{_fmt(month_t['median'])} (month) |",
        f"| VZM dwell P90 (min), median over the days | {_fmt(_median(p90s), '.0f')} | "
        f"{_fmt(month_d['p90'], '.0f')} (month) |",
        f"| VZM stops over 30 min, median over the days | {_fmt(_median(shares), '.1%')} | "
        f"{_fmt(month_d['share_over_long'], '.1%')} (month) |",
        f"| Section punctuality A2 (%), median over the days | {_fmt(_median(a2), '.1f')} | n/a |",
        "",
        "| Day | Through-transit twin (h) | n | BL-5 (h) | n | VZM P90 twin (min) | BL-5 "
        "| VZM > 30 min twin | BL-5 | A2 twin (%) | Trains exited |",
        "|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for r in days:
        out.append(
            f"| {r['day']} | {_fmt(r['twin_transit_median_h'])} | {r['twin_transit_n']} | "
            f"{_fmt(r['hist_transit_median_h'])} | {_fmt(r['hist_transit_n'], '.0f')} | "
            f"{_fmt(r['twin_vzm_p90_min'], '.0f')} | {_fmt(r['hist_vzm_p90_min'], '.0f')} | "
            f"{_fmt(r['twin_vzm_share_long'], '.1%')} | {_fmt(r['hist_vzm_share_long'], '.1%')} | "
            f"{_fmt(r['twin_a2_pct'], '.1f')} | {_fmt(r['twin_trains_exited'], '.0f')} |"
        )
    out += [
        "",
        "BL-5 is a reference anchor, not a like-for-like comparator (spec §12.2): the log includes causes "
        "the twin does not model (loco and crew availability, yard and branch interactions, failures). A "
        "gap is the twin-realism gap of DSC-20 (RK-23), documented, not tuned away. The DSS-against-greedy "
        "criteria "
        "on these days (DSC-21, DSC-22) are measured by the evaluation runner (#168, #170).",
        "",
    ]
    return "\n".join(out)


def run_days(days: set[int] | None = None, world: run.World | None = None, write: bool = False) -> str:
    """Replay the chosen real days of SCN-22 (all when ``days`` is empty) and render the report."""
    world = world or run.load_world()
    reference = json.loads(REFERENCE_JSON.read_text(encoding="utf-8"))
    sc = next(s for s in scenario.load_library_v1() if s.id == "SCN-22")
    rows = load_rows() if write else {}
    for d in scenario.day_scenarios(sc):
        if days and d.wtt_date.day not in days:
            continue
        row = day_row(world, d, reference)
        rows[row["day"]] = row
        transit = _fmt(row["twin_transit_median_h"])
        print(f"{row['day']}: through-transit {transit} h, A2 {row['twin_a2_pct']}")
    text = render(rows, reference)
    if write:
        save_rows(rows)
        REPORT_MD.write_text(text, encoding="utf-8", newline="\n")
    return text


def parse_days(spec: str | None) -> set[int]:
    """``1-9,15``: days of the month."""
    out: set[int] = set()
    for part in (spec or "").split(","):
        if "-" in part:
            a, b = part.split("-")
            out |= set(range(int(a), int(b) + 1))
        elif part.strip():
            out.add(int(part))
    return out
