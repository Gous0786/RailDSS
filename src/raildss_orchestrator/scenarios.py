"""KPIs of the v0 disruption scenarios, under BL-0 and under the decision loop (issue #57; FR-SCN-04).

* **BL-0** (every scenario): the twin plays the scenario with its injected disruptions and its seed, nothing
  else changes; the KPIs come from the ground-truth events (FR-KPI-01).
* **Decision loop** (scenarios whose disruptions are all line blocks, SCN-05 and SCN-20): the loop plans for
  the blocked line (the greedy dispatcher models closures) in a window around the block, verifies and accepts
  its options, and the day is compared with BL-0 under the same closure (FR-KPI-05). The other disruption
  types (a loop out of use, a speed restriction, a late train) are not modelled by the planner yet: they have
  a BL-0 row only. The loop runs on the closure as a twin directive, not through the injector.
"""

from __future__ import annotations

from typing import Any

from raildss_dss.kpi import KpiReport
from raildss_optimiser.greedy import GreedyDispatcher
from raildss_orchestrator.loop import Disruption, Orchestrator, RunSummary
from raildss_orchestrator.twin import TwinDss, TwinPlanner, day_kpis
from raildss_twin import run, scenario
from raildss_twin.kpi_eval import run_arm
from raildss_twin.scenario import Scenario

SECONDS_PER_MIN = 60
SECONDS_PER_HOUR = 3600
LEAD_S = 15 * SECONDS_PER_MIN  # the loop starts this long before the first disruption
SPAN_S = 90 * SECONDS_PER_MIN  # and runs this long
NOTICE_S = 30 * SECONDS_PER_MIN  # a closure is known this long before it starts
TICK_S = 120.0
SHOWN = (
    "A2_section_punctuality_pct",
    "A4_mean_arrival_delay_min",
    "A5_weighted_delay_train_min",
    "A6_mean_exit_delay_min",
    "A6_p90_exit_delay_min",
    "B1_trains_exited",
    "C2_freight_detention_h",
    "F1_unplanned_stops",
)


def bl0(world: run.World, sc: Scenario) -> KpiReport:
    """The scenario under BL-0: its seed, freight day and injected disruptions, no decision support."""
    kw = scenario.run_kwargs(sc)
    return run_arm(
        world,
        sc.wtt_date,
        "BL-0",
        sc.id,
        directives=kw["directives"],
        seed=kw["seed"],
        day_instance=kw["day_instance"],
        setup=kw["setup"],
    )


def loopable(sc: Scenario) -> bool:
    return bool(sc.disruptions) and all(d.type == "line_block" for d in sc.disruptions)


def with_loop(world: run.World, sc: Scenario) -> tuple[RunSummary, dict[str, Any]]:
    """The decision loop around a line block, and the day's KPIs against BL-0 under the same closure."""
    closures = GreedyDispatcher(world).closures_of(sc)
    first = min(d.start_s for d in sc.disruptions)
    from_s, to_s = first - LEAD_S, first - LEAD_S + SPAN_S
    day = sc.wtt_date
    dss = TwinDss(world, day, until_s=to_s, closures=closures)
    planner = TwinPlanner(world, day, cpsat_enabled=False)
    loop = Orchestrator(
        world.register,
        dss,
        planner,
        disruptions=tuple(Disruption(c, c.start_s - NOTICE_S) for c in closures),
    )
    summary = loop.run(from_s, to_s, TICK_S)
    holds, lines = loop.commitments()
    comparison = day_kpis(world, day, closures=closures, exit_windows={}, holds=holds, lines=lines)
    return summary, comparison


def render(
    rows: list[tuple[Scenario, KpiReport]], loops: list[tuple[Scenario, RunSummary, dict[str, Any]]]
) -> str:
    out = [
        "# KPIs of the v0 scenarios (issue #57)",
        "",
        "Generated by `python -m raildss_orchestrator scenarios --report docs/kpi/scenarios-v0.md`.",
        "",
        "## BL-0: the twin with the scripted disruptions, no decision support",
        "",
        "| Scenario | Disruptions | "
        + " | ".join(k.split("_", 1)[0] + " " + k.split("_", 1)[1] for k in SHOWN)
        + " |",
        "|---|---|" + "---:|" * len(SHOWN),
    ]
    for sc, rep in rows:
        kinds = ", ".join(sorted({d.type for d in sc.disruptions})) or "none"
        out.append(f"| {sc.id} | {kinds} | " + " | ".join(f"{rep.kpis[k]:g}" for k in SHOWN) + " |")
    out += [
        "",
        "## Decision loop on the line-block scenarios",
        "",
        "The loop plans for the blocked line in a window around it, with greedy options verified by gates "
        "G0-G3 and accepted by the evaluation policy; both arms of the day run under the same closure. "
        "The closure is a twin directive, not the injector's single-line working, so the BL-0 column "
        "here differs from the BL-0 table above.",
    ]
    for sc, summary, comp in loops:
        verified = sum(c.verified for cy in summary.cycles for c in cy.candidates)
        built = sum(len(cy.candidates) for cy in summary.cycles)
        dss, base = comp["arms"]["DSS"], comp["arms"]["BL-0"]
        out += [
            "",
            f"### {sc.id}: {sc.title}",
            "",
            f"Window {summary.from_s / SECONDS_PER_HOUR:.2f}-{summary.to_s / SECONDS_PER_HOUR:.2f} h, "
            f"{len(summary.cycles)} plans ({verified} of {built} candidate plans passed G0-G3), "
            f"{summary.accepted} recommendations accepted, {summary.orders} orders.",
            "",
            "| KPI | DSS | BL-0 | Delta |",
            "|---|---:|---:|---:|",
        ]
        out += [f"| {k} | {dss[k]:g} | {base[k]:g} | {dss[k] - base[k]:+.2f} |" for k in SHOWN]
    return "\n".join(out) + "\n"


def run_all(
    world: run.World, ids: list[str], *, with_loops: bool
) -> tuple[list[tuple[Scenario, KpiReport]], list[tuple[Scenario, RunSummary, dict[str, Any]]]]:
    library = [s for s in scenario.load_library() if s.executable and (not ids or s.id in ids)]
    rows = [(s, bl0(world, s)) for s in library]
    loops = []
    if with_loops:
        for s in library:
            if loopable(s):
                summary, comp = with_loop(world, s)
                loops.append((s, summary, comp))
    return rows, loops
