"""Alert load on the nominal days (spec §12.4 DSC-09; R02 H1, H2; issue #163).

Runs the DSS chain (DS-1, DS-3, DS-4, DS-5) over a whole twin day with no disruption and no planner, tick by
tick, and counts the alerts it would raise (:class:`raildss_dss.alert_kpi.AlertLog`): alerts per
controller-hour against the budget of 6, and flood events. The nominal scenarios are SCN-01 and SCN-22
(a real freight day and the WTT of its date, no injected disruption).
"""

from __future__ import annotations

from typing import Any

from raildss_dss.alert_kpi import AlertKpis, AlertLog
from raildss_orchestrator.report import alert_rows
from raildss_orchestrator.twin import TwinDss
from raildss_twin import run
from raildss_twin.scenario import Scenario

SECONDS_PER_HOUR = 3600
SECONDS_PER_DAY = 24 * SECONDS_PER_HOUR
NOMINAL = ("SCN-01", "SCN-22")


def run_day(
    world: run.World, sc: Scenario, *, tick_s: float, from_s: float = 0.0, to_s: float = SECONDS_PER_DAY
) -> AlertKpis:
    """The alerts of the DSS chain on a scenario's day between ``from_s`` and ``to_s``."""
    dss = TwinDss(world, sc.wtt_date, profile=sc.degradation_profile, until_s=to_s)
    log = AlertLog(world.register)
    t = from_s
    while t <= to_s:
        view = dss.advance(t)
        log.record(t, view.conflicts, view.alerts)
        t += tick_s
    return log.kpis(from_s, to_s)


def render(rows: list[tuple[Scenario, AlertKpis]], *, tick_s: float) -> str:
    out = [
        "# Alert load on the nominal days (DSC-09, R02 H1-H2; issue #163)",
        "",
        "Generated by `python -m raildss_orchestrator alert-load --report docs/kpi/alert-load-nominal.md`.",
        "",
        "The DSS chain (DS-1, DS-3, DS-4, DS-5) over the whole day of each nominal scenario, with no",
        f"disruption and no planner, every {tick_s:g} s of the scenario clock. An alert is a conflict newly",
        "reported with priority P1 to P3, or a data-quality alert of those priorities; a conflict is one",
        "alert while the detector keeps reporting it. There is no alert manager (DS-14) yet, so nothing is",
        "grouped or suppressed: these are the raw alerts a controller would get, an upper bound for the",
        "managed load.",
        "Targets on nominal scenarios (DSC-09): at most 6 alerts per controller-hour and no flood event",
        "(more than 10 alerts in 10 min).",
    ]
    for sc, k in rows:
        out += ["", f"## {sc.id}: {sc.title}", ""]
        out += [f"Day {sc.wtt_date}, profile {sc.degradation_profile}.", ""]
        out += alert_rows(k.as_dict())
    return "\n".join(out) + "\n"


def summary(rows: list[tuple[Scenario, AlertKpis]]) -> dict[str, Any]:
    return {sc.id: k.as_dict() for sc, k in rows}
